// The oracle: run tslua under real Lua 5.4 (wasmoon) on every input in
// oracle/inputs/ in both lib modes, and store what it prints.
//
//   vp run oracle                  rebuild oracle/expected/ and oracle/manifest.json
//   vp run oracle -- --verify      rerun and compare with the stored outputs (writes nothing)
//   vp run oracle -- --only NAME   only inputs whose name contains NAME (no manifest)
//   vp run oracle -- --lib mini    only one lib mode
//
// Each input runs twice in fresh Lua states: once plain (wall time) and once
// under a count hook of 1 (exact VM instruction count); both must print the
// same thing.
import { mkdirSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { runPool, type Job } from "./pool.ts";
import { argsFor, createFactory, libs, loadCost, root, check, type Lib } from "./tslua.ts";

const inputsDir = join(root, "oracle/inputs");
const expectedDir = join(root, "oracle/expected");
const manifestPath = join(root, "oracle/manifest.json");

export function listInputs(): string[] {
  const out: string[] = [];
  const walk = (dir: string) => {
    for (const entry of readdirSync(dir).sort()) {
      const p = join(dir, entry);
      if (statSync(p).isDirectory()) walk(p);
      else if (p.endsWith(".ts")) out.push(relative(inputsDir, p).replace(/\.ts$/, ""));
    }
  };
  walk(inputsDir);
  return out;
}

export const inputPath = (name: string): string => join(inputsDir, `${name}.ts`);
export const expectedPath = (name: string, lib: Lib["name"]): string =>
  join(expectedDir, `${name}.${lib}.txt`);

const MINI_HEADER =
  "// Generated by scripts/oracle.ts from tslua's tsctests.tscDefaultLibContent. Do not edit.\n";

/** lua/lib.mini.d.ts: tslua's stand-in default lib, read out of tslua itself. */
async function writeMiniLib(): Promise<boolean> {
  const factory = await createFactory();
  const lua = await factory.createEngine();
  try {
    const text = (await lua.doString(
      `package.path = "/t/src/?.lua;/t/src/?/init.lua"; return require("tslua.execute.tsctests").tscDefaultLibContent`,
    )) as string;
    const content = MINI_HEADER + text + "\n";
    const path = libs.mini.path;
    let old = "";
    try {
      old = readFileSync(path, "utf8");
    } catch {}
    if (old !== content) writeFileSync(path, content);
    return old !== content;
  } finally {
    lua.global.close();
  }
}

const quantiles = (xs: number[]) => {
  const s = [...xs].sort((a, b) => a - b);
  const q = (p: number) => s[Math.min(s.length - 1, Math.floor(p * (s.length - 1) + 0.5))]!;
  return {
    n: s.length,
    min: s[0]!,
    p10: q(0.1),
    median: q(0.5),
    p90: q(0.9),
    max: s[s.length - 1]!,
  };
};

const diagnosticCodes = (output: string): string[] =>
  [...new Set([...output.matchAll(/error (TS\d+)/g)].map((m) => m[1]!))].sort();

async function main() {
  const argv = process.argv.slice(2);
  const verify = argv.includes("--verify");
  const only = argv.includes("--only") ? argv[argv.indexOf("--only") + 1]! : undefined;
  const libNames = (
    argv.includes("--lib") ? [argv[argv.indexOf("--lib") + 1]!] : ["mini", "es5"]
  ) as Lib["name"][];
  const partial = only !== undefined || libNames.length !== 2;

  if (!verify && (await writeMiniLib())) console.log("wrote lua/lib.mini.d.ts");

  const names = listInputs().filter((n) => only === undefined || n.includes(only));
  const libSources = Object.fromEntries(
    libNames.map((l) => [l, readFileSync(libs[l].path, "utf8")]),
  );
  const jobs: Job[] = [];
  const meta: { name: string; lib: Lib["name"] }[] = [];
  for (const name of names)
    for (const lib of libNames) {
      meta.push({ name, lib });
      jobs.push({
        id: jobs.length,
        source: readFileSync(inputPath(name), "utf8"),
        lib,
        libSource: libSources[lib],
        options: { count: true },
        twice: true,
      });
    }

  console.log(`${names.length} inputs x ${libNames.join(",")} = ${jobs.length} checks`);
  const t0 = performance.now();
  const results = await runPool(jobs, (r, done) => {
    if (done % 50 === 0 || done === jobs.length)
      console.log(`  ${done}/${jobs.length} (${((performance.now() - t0) / 1000).toFixed(0)} s)`);
    if (!r.same) console.log(`  NONDETERMINISTIC: ${meta[r.id]!.name}.${meta[r.id]!.lib}`);
  });

  let mismatches = 0;
  for (const r of results) {
    const { name, lib } = meta[r.id]!;
    const path = expectedPath(name, lib);
    if (verify) {
      let old: string | undefined;
      try {
        old = readFileSync(path, "utf8");
      } catch {}
      if (old !== r.result.output) {
        mismatches++;
        console.log(`  MISMATCH ${name}.${lib}`);
      }
    } else {
      mkdirSync(dirname(path), { recursive: true });
      writeFileSync(path, r.result.output);
    }
  }
  if (verify) {
    console.log(mismatches === 0 ? "all outputs match" : `${mismatches} mismatches`);
    if (verify && !partial) compareCounts(results, meta);
    process.exitCode = mismatches === 0 ? 0 : 1;
    return;
  }
  if (partial) return;

  // Remove expected files of inputs that no longer exist.
  const keep = new Set(meta.map(({ name, lib }) => expectedPath(name, lib)));
  const sweep = (dir: string) => {
    for (const entry of readdirSync(dir)) {
      const p = join(dir, entry);
      if (statSync(p).isDirectory()) sweep(p);
      else if (!keep.has(p)) rmSync(p);
    }
  };
  sweep(expectedDir);

  const load = await loadCost();
  const oneLiner = await check("const x: number = 'hello';\n", libs.mini, { count: true });
  const oneLinerEs5 = await check("const x: number = 'hello';\n", libs.es5, {
    count: true,
  });
  const empty = await check("", libs.mini, { count: true });

  const entries = results.map((r) => {
    const { name, lib } = meta[r.id]!;
    return {
      input: name,
      lib,
      inputBytes: Buffer.byteLength(jobs[r.id]!.source),
      instructions: r.result.instructions!,
      ms: Math.round(r.plainMs! * 10) / 10,
      msHooked: Math.round(r.result.ms * 10) / 10,
      heapAfterCheckKB: Math.round(r.result.heapAfterCheckKB),
      outputBytes: Buffer.byteLength(r.result.output),
      status: r.result.status,
      codes: diagnosticCodes(r.result.output),
    };
  });
  const summary = Object.fromEntries(
    libNames.map((lib) => {
      const es = entries.filter((e) => e.lib === lib);
      return [
        lib,
        {
          instructions: quantiles(es.map((e) => e.instructions)),
          ms: quantiles(es.map((e) => e.ms)),
          outputBytes: quantiles(es.map((e) => e.outputBytes)),
          clean: es.filter((e) => e.outputBytes === 0).length,
          crashed: es.filter((e) => e.status === -1).map((e) => e.input),
        },
      ];
    }),
  );

  const manifest = {
    generated: "by scripts/oracle.ts (vp run oracle); do not edit",
    tslua: "vendor/tslua (github.com/Yhozen/tslua), see git submodule status",
    lua: "Lua 5.4 via wasmoon 1.16.0",
    counting:
      "instructions = Lua VM instructions inside tsc.check, counted with debug.sethook(f, '', 1) (a count hook every instruction, exact). Loading (require 'tsc') is not included; see load.",
    timing:
      "ms = wall time of an unhooked tsc.check in a fresh Lua state (worker threads in parallel, so noisy); msHooked = the same under the count hook.",
    harness: "lua/tsc.lua; files /p/<lib file> and /p/main.ts, cwd /p",
    args: Object.fromEntries(libNames.map((l) => [l, argsFor(libs[l])])),
    libFiles: {
      mini: "lua/lib.mini.d.ts",
      es5: "vendor/tslua/src/tslua/bundled/libs/lib.es5.d.ts",
    },
    load: {
      instructions: load.instructions,
      ms: Math.round(load.ms),
      heapKB: Math.round(load.heapKB),
    },
    reference: {
      emptyFileMini: empty.instructions,
      oneLinerMini: oneLiner.instructions,
      oneLinerEs5: oneLinerEs5.instructions,
      oneLinerOutput: oneLiner.output,
    },
    summary,
    entries,
  };
  writeFileSync(manifestPath, JSON.stringify(manifest, null, 1) + "\n");
  console.log(
    JSON.stringify({ load: manifest.load, reference: manifest.reference, summary }, null, 1),
  );
}

/** In --verify mode, also check that instruction counts are reproducible. */
function compareCounts(
  results: { id: number; result: { instructions?: number } }[],
  meta: { name: string; lib: string }[],
) {
  let manifest: { entries: { input: string; lib: string; instructions: number }[] };
  try {
    manifest = JSON.parse(readFileSync(manifestPath, "utf8"));
  } catch {
    return;
  }
  const old = new Map(manifest.entries.map((e) => [`${e.input}.${e.lib}`, e.instructions]));
  let diff = 0;
  for (const r of results) {
    const key = `${meta[r.id]!.name}.${meta[r.id]!.lib}`;
    if (old.get(key) !== r.result.instructions) {
      diff++;
      console.log(`  COUNT ${key}: ${old.get(key)} -> ${r.result.instructions}`);
    }
  }
  console.log(diff === 0 ? "all instruction counts match" : `${diff} instruction counts differ`);
}

if (import.meta.main) await main();
