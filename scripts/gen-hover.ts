// Tables for src/hover.ts (vp run gen:hover -> src/hover.gen.ts): a type-level
// Pearson hash of the source that picks where in the fuel pool a hover's run
// draws its budget resets, so that different checks in one editor session do
// not reuse each other's (already resolved, hence useless) pool nodes.
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { root } from "./tslua.ts";

// xorshift32, fixed seed: the tables never change unless this file does.
let seed = 0x9e3779b9;
const rnd = () => {
  seed ^= seed << 13;
  seed >>>= 0;
  seed ^= seed >>> 17;
  seed ^= seed << 5;
  seed >>>= 0;
  return seed;
};
const perm = (n: number) => {
  const p = Array.from({ length: n }, (_, i) => i);
  for (let i = n - 1; i > 0; i--) {
    const j = rnd() % (i + 1);
    [p[i], p[j]] = [p[j]!, p[i]!];
  }
  return p;
};

const lit = JSON.stringify;
const obj = (entries: [string, string][]) =>
  `{ ${entries.map(([k, v]) => `${lit(k)}: ${lit(v)}`).join("; ")} }`;

/** One byte (a character U+0000..U+00FF) to 0..63. */
const code = Array.from({ length: 256 }, () => rnd() % 64);
/** Pearson step tables: M[h][c] = T[h xor c]. */
const step = () => {
  const t = perm(64);
  return Array.from({ length: 64 }, (_, h) =>
    obj(Array.from({ length: 64 }, (_, c) => [String(c), String(t[h ^ c])])),
  );
};
const table = (name: string, doc: string, rows: string[]) =>
  `/** ${doc} */\nexport interface ${name} {\n${rows.map((r, h) => `  ${lit(String(h))}: ${r};`).join("\n")}\n}\n`;
const m1 = step();
const m2 = step();
const other1 = perm(64);
const other2 = perm(64);

const text = `// Generated by scripts/gen-hover.ts (vp run gen:hover); do not edit.

/** A character (one byte, U+0000..U+00FF) to 0..63. */
export interface Code ${obj(code.map((c, i) => [String.fromCharCode(i), String(c)]))}
${table("M1", "Pearson step of the first hash: M1[h][code] = T1[h xor code].", m1)}
${table("M2", "Pearson step of the second hash.", m2)}
/** The first fuel-pool chunk of a hover's run: 60 * h. */
export interface KStart ${obj(Array.from({ length: 64 }, (_, h) => [String(h), String(60 * h)]))}
/** The second and third pool slots of a run whose first slot is h. */
export interface Other1 ${obj(other1.map((v, h) => [String(h), String(v)]))}
export interface Other2 ${obj(other2.map((v, h) => [String(h), String(v)]))}
/** The slot after h (a new lap of the pool). */
export interface Next ${obj(Array.from({ length: 64 }, (_, h) => [String(h), String((h + 1) % 64)]))}
`;
writeFileSync(join(root, "src/hover.gen.ts"), text);
console.log(`wrote src/hover.gen.ts (${(text.length / 1e3).toFixed(0)} KB)`);
