// The types gate: tslua in the type checker (the image of `vp run build`, via
// src/index.ts) must print exactly what tslua prints under real Lua
// (oracle/expected/), checked with the tsrs CLI in chained budget chunks.
//
//   vp run gate:types                 the 20 inputs cheapest on the reference (mini lib)
//   vp run gate:types -- --all        every input
//   vp run gate:types -- --n 40       the 40 cheapest
//   vp run gate:types -- --only NAME  inputs whose name contains NAME
//   vp run gate:types -- --lib es5    lib mode: mini (default), es5 or both
//   vp run gate:types -- --jobs 3     tsrs processes in parallel (each takes 4-8 GB)
//
// Per input it writes .run/gate/<lib>/<input>/run.ts: `type S0 =
// TSStart<source>`, one `type Sk = TSStep<Sk-1>` statement per chunk (the CLI
// zeroes its instantiation counter per statement), a probe per chunk that
// reports the state's tag (a TS2322 on a `0`), the output, and an exact
// equality assertion with the expected text. The number of chunks comes from
// the reference's counters with headroom; a finished state stays finished, so
// extra chunks cost nothing.
//
// Reported per input: pass/fail, the chunk at which the run ended (or the
// last one reached), instantiations, check time, peak memory (max RSS), the
// reference's IR ops from the image (oracle/ref-image-manifest.json) and the
// reference's op count at its first float operation other than a table key,
// a unary op or an equality (where the types stop until the float prelude exists), and the
// error if the run raised one. A summary goes to .run/gate/<lib>/report.json.
import { spawn } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import type { Snapshot } from "../vendor/lua-in-types/src/aot/ref/snapshot.ts";
import { toBytes } from "../vendor/lua-in-types/src/aot/ref/value.ts";
import { DRIVE, imageDir, libFile, progFile } from "./build-image.ts";
import { fromImage, imagePath, refProgram, runCheck } from "./luaref.ts";
import { expectedPath, inputPath } from "./oracle.ts";
import { libs, root, type Lib } from "./tslua.ts";

interface RefEntry {
  input: string;
  lib: Lib["name"];
  ops: number;
  blocks: number;
  luaCalls: number;
  builtinCalls: Record<string, number>;
  metamethods: Record<string, number>;
}

export interface GateRow {
  input: string;
  lib: Lib["name"];
  pass: boolean;
  /** Chunks written; the chunk at which the run ended (D or X), or undefined if it did not. */
  chunks: number;
  endedAt?: number;
  /** The last chunk whose state resolved (not any or never), and its tag. */
  lastGood: number;
  lastTag: string;
  output: string;
  error?: string;
  otherErrors: string[];
  instantiations: number;
  checkSeconds: number;
  wallSeconds: number;
  peakBytes: number;
  refOps: number;
  refOpsAtFloat?: number;
  refFloatKind?: string;
}

const argv = process.argv.slice(2);
const opt = (k: string) => (argv.includes(k) ? argv[argv.indexOf(k) + 1] : undefined);
const sum = (o: Record<string, number>) => Object.values(o).reduce((a, b) => a + b, 0);

/** Budget chunks a check needs, from the reference's counters (with headroom). */
export const chunksFor = (r: RefEntry): number => {
  const steps = 3 * (r.luaCalls + sum(r.metamethods) + sum(r.builtinCalls)) + r.blocks / 4 + 8;
  return Math.ceil((1.3 * steps) / DRIVE) + 10;
};

const lit = JSON.stringify;

/** The CLI entry of one check. */
export function entryText(source: string, lib: Lib["name"], chunks: number, expected: string) {
  const lines = [
    "// Generated by scripts/types-gate.ts; do not edit.",
    `import type { TSStart, TSStep, TSOutput, TSTag } from "../../../../src/index.ts";`,
    "type Equal<A, B> = (<T>() => T extends A ? 1 : 2) extends <T>() => T extends B ? 1 : 2 ? true : false;",
    'type Stat<S> = 0 extends 1 & S ? "any" : [S] extends [never] ? "never" : TSTag<S>;',
    `type S0 = TSStart<${lit(toBytes(source))}, ${lit(lib)}>;`,
  ];
  for (let k = 1; k <= chunks; k++) lines.push(`type S${k} = TSStep<S${k - 1}>;`);
  const first = lines.length + 1;
  for (let k = 1; k <= chunks; k++) lines.push(`export const p${k}: 0 = null! as Stat<S${k}>;`);
  lines.push(`export const out: 0 = null! as TSOutput<S${chunks}>;`);
  lines.push(`export const ok: Equal<TSOutput<S${chunks}>, ${lit(toBytes(expected))}> = true;`);
  return { text: lines.join("\n") + "\n", probeLine: first, outLine: first + chunks };
}

/** A printed string literal type ("..." with escapes) back to its text. */
const unquote = (t: string): string => {
  try {
    return JSON.parse(t) as string;
  } catch {
    return t;
  }
};

function runTsrs(dir: string): Promise<{ out: string; wall: number; peak: number }> {
  const t0 = performance.now();
  return new Promise((resolve, reject) => {
    const p = spawn(
      "/usr/bin/time",
      [
        "-l",
        join(root, "node_modules/.bin/tsrs"),
        "--noEmit",
        "--fast",
        "--extendedDiagnostics",
        "--pretty",
        "false",
        "--noErrorTruncation",
        "-p",
        dir,
      ],
      { env: { ...process.env, TSRS_FAST: "1" } },
    );
    let out = "";
    p.stdout.on("data", (d: Buffer) => (out += d.toString()));
    p.stderr.on("data", (d: Buffer) => (out += d.toString()));
    p.on("error", reject);
    p.on("close", () => {
      const peak = Number(/(\d+)\s+maximum resident set size/.exec(out)?.[1] ?? 0);
      resolve({ out, wall: (performance.now() - t0) / 1000, peak });
    });
  });
}

/** The reference's op count at the first float operation the types do not compute inline yet. */
function refFloat(
  program: ReturnType<typeof refProgram>,
  image: Snapshot,
  lib: Lib,
  source: string,
): { ops?: number; kind?: string } {
  const interp = fromImage(program, image);
  // Interp.fl (private) counts every float operation.
  const hook = interp as unknown as { fl: (k: string) => void };
  const orig = hook.fl.bind(interp);
  let hit: { ops: number; kind: string } | undefined;
  hook.fl = (k: string) => {
    if (hit === undefined && !/^(key|unop|cmp\.eq)/.test(k))
      hit = { ops: interp.counters.ops, kind: k };
    orig(k);
  };
  runCheck(interp, program, lib, source);
  return hit ?? {};
}

async function main() {
  for (const f of [progFile, libFile("mini"), libFile("es5")])
    if (!existsSync(join(imageDir, f))) throw new Error(`image/${f} is missing: run vp run build`);
  const manifest = JSON.parse(
    readFileSync(join(root, "oracle/ref-image-manifest.json"), "utf8"),
  ) as { entries: RefEntry[] };
  const libArg = opt("--lib") ?? "mini";
  const libNames: Lib["name"][] = libArg === "both" ? ["mini", "es5"] : [libArg as Lib["name"]];
  const jobs = Number(opt("--jobs") ?? 3);
  const only = opt("--only");
  // Inputs ordered by the reference's cost in the mini lib mode.
  let inputs = manifest.entries
    .filter((e) => e.lib === "mini")
    .sort((a, b) => a.ops - b.ops)
    .map((e) => e.input);
  if (only !== undefined) inputs = inputs.filter((n) => n.includes(only));
  else if (!argv.includes("--all")) inputs = inputs.slice(0, Number(opt("--n") ?? 20));

  const program = refProgram();
  const rows: GateRow[] = [];
  for (const libName of libNames) {
    const lib = libs[libName];
    const image = JSON.parse(readFileSync(imagePath(libName), "utf8")) as Snapshot;
    const work = inputs.map((input) => {
      const ref = manifest.entries.find((e) => e.input === input && e.lib === libName)!;
      const source = readFileSync(inputPath(input), "utf8");
      const expected = readFileSync(expectedPath(input, libName), "utf8");
      const fl = refFloat(program, image, lib, source);
      return { input, ref, source, expected, fl };
    });
    console.log(
      `${libName}: ${work.length} inputs, ${jobs} tsrs at a time (reference float sites done)`,
    );
    let next = 0;
    await Promise.all(
      Array.from({ length: Math.min(jobs, work.length) }, async () => {
        while (next < work.length) {
          const w = work[next++]!;
          const row = await gateOne(w, libName);
          rows.push(row);
          console.log(rowText(row));
        }
      }),
    );
    const mine = rows.filter((r) => r.lib === libName);
    const dir = join(root, ".run/gate", libName);
    writeFileSync(join(dir, "report.json"), JSON.stringify(mine, null, 1) + "\n");
    console.log(
      `${libName}: ${mine.filter((r) => r.pass).length}/${mine.length} pass; report in .run/gate/${libName}/report.json`,
    );
  }
  if (rows.some((r) => !r.pass)) process.exitCode = 1;
}

async function gateOne(
  w: {
    input: string;
    ref: RefEntry;
    source: string;
    expected: string;
    fl: { ops?: number; kind?: string };
  },
  lib: Lib["name"],
): Promise<GateRow> {
  const chunks = chunksFor(w.ref);
  const dir = join(root, ".run/gate", lib, w.input.replaceAll("/", "__"));
  mkdirSync(dir, { recursive: true });
  const e = entryText(w.source, lib, chunks, w.expected);
  writeFileSync(join(dir, "run.ts"), e.text);
  writeFileSync(
    join(dir, "tsconfig.json"),
    JSON.stringify({
      extends: "../../../../tsconfig.json",
      include: ["run.ts"],
      exclude: [],
      compilerOptions: { noUnusedLocals: false },
    }) + "\n",
  );
  const { out, wall, peak } = await runTsrs(dir);
  writeFileSync(join(dir, "tsrs.log"), out);
  const tags = new Map<number, string>();
  let output = "";
  let pass = true;
  const otherErrors: string[] = [];
  for (const m of out.matchAll(/run\.ts\((\d+),\d+\): error (TS\d+): (.*)/g)) {
    const line = Number(m[1]);
    const t = /^Type '([\s\S]*)' is not assignable to type '0'\.$/.exec(m[3]!);
    if (line >= e.probeLine && line < e.outLine && t)
      tags.set(line - e.probeLine + 1, unquote(t[1]!));
    else if (line === e.outLine && t) output = unquote(t[1]!);
    else if (line === e.outLine + 1) pass = false;
    else otherErrors.push(`${line}: ${m[2]} ${m[3]!.slice(0, 200)}`);
  }
  // A probe without an error means the tag was 0 (impossible) or the line did not check.
  let endedAt: number | undefined;
  let lastGood = 0;
  let lastTag = "";
  for (let k = 1; k <= chunks; k++) {
    const t = tags.get(k) ?? "?";
    if (t === "any" || t === "never" || t === "?") break;
    lastGood = k;
    lastTag = t;
    if (t === "D" || t === "X") {
      endedAt = k;
      break;
    }
  }
  if (otherErrors.length > 0) pass = false;
  const num = (re: RegExp) => Number(re.exec(out)?.[1] ?? NaN);
  return {
    input: w.input,
    lib,
    pass,
    chunks,
    endedAt,
    lastGood,
    lastTag,
    output,
    error: output.startsWith("error: ") ? output.slice(7).trimEnd() : undefined,
    otherErrors,
    instantiations: num(/Instantiations:\s+(\d+)/),
    checkSeconds: num(/Check time:\s+([\d.]+)s/),
    wallSeconds: wall,
    peakBytes: peak,
    refOps: w.ref.ops,
    refOpsAtFloat: w.fl.ops,
    refFloatKind: w.fl.kind,
  };
}

export const rowText = (r: GateRow): string =>
  [
    r.pass ? "PASS" : "FAIL",
    `${r.lib}/${r.input}`,
    r.endedAt !== undefined
      ? `ended at chunk ${r.endedAt}/${r.chunks} (${r.lastTag})`
      : `reached chunk ${r.lastGood}/${r.chunks} (${r.lastTag || "nothing"})`,
    `${(r.instantiations / 1e6).toFixed(0)}M inst`,
    `check ${r.checkSeconds.toFixed(1)} s (wall ${r.wallSeconds.toFixed(1)} s)`,
    `peak ${(r.peakBytes / 2 ** 30).toFixed(1)} GB`,
    `ref ${r.refOps} ops` +
      (r.refOpsAtFloat !== undefined
        ? `, first float op (${r.refFloatKind}) at ${r.refOpsAtFloat} (${((100 * r.refOpsAtFloat) / r.refOps).toFixed(0)}%)`
        : ", no float op"),
    ...(r.error ? [`error: ${r.error}`] : []),
    ...(r.otherErrors.length ? [`other: ${r.otherErrors.slice(0, 3).join(" | ")}`] : []),
  ].join("  ");

if (import.meta.main) await main();
