// The types gate: tslua in the type checker (the image of `vp run build`, via
// src/index.ts) must print exactly what tslua prints under real Lua
// (oracle/expected/), checked with the tsrs CLI in chained budget chunks.
//
//   vp run gate:types                 the 20 inputs cheapest on the reference (mini lib)
//   vp run gate:types -- --all        every input
//   vp run gate:types -- --n 40       the 40 cheapest
//   vp run gate:types -- --only NAME  inputs whose name contains NAME
//   vp run gate:types -- --lib es5    lib mode: mini (default), es5 or both
//   vp run gate:types -- --jobs 3     tsrs processes in parallel (each takes 4-8 GB)
//   vp run gate:types -- --drive 10   trampoline steps per chunk (default: the image's)
//   vp run gate:types -- --resume     keep per-input results newer than the image
//   vp run gate:types -- --timeout 900  seconds per tsrs run (default 900)
//   vp run gate:types -- --max-ops 10000000  skip inputs whose reference run is longer
//   vp run gate:types -- --doc        write docs/GATE.md from the results (with --all --lib both)
//
// Per input it writes .run/gate/<lib>/<input>/run.ts: `type S0 =
// TSStart<source>`, one `type Sk = TSStep<Sk-1>` statement per chunk (the CLI
// zeroes its instantiation counter per statement), a probe per chunk that
// reports the state's tag (a TS2322 on a `0`), the output, and an exact
// equality assertion with the expected text. The number of chunks comes from
// the reference's counters with headroom; a finished state stays finished, so
// extra chunks cost nothing.
//
// Reported per input: pass/fail, the chunk at which the run ended (or the
// last one reached), instantiations, check time, peak memory (max RSS), the
// reference's IR ops from the image (oracle/ref-image-manifest.json), and the
// error if the run raised one. A summary goes to .run/gate/<lib>/report.json,
// each input's row to .run/gate/<lib>/<input>/row.json.
//
// A failure is classified (GateRow.kind): "TS2589 count" (one chunk, or one
// trampoline step, went over the 5M-instantiation budget) or "TS2589 depth"
// (one step failed below it: instantiation or tail-recursion depth), told
// apart by rerunning the failing chunk one step per statement; "runtime gap"
// (Lua raised "... is not supported in types"), "Lua error" (any other error
// the run raised), "wrong output" (the first differing line), "unfinished"
// (no end within the chunks written), "broken state" (a chunk was any or
// never without a diagnostic), "timeout" and "skipped".
import { spawn } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { toBytes } from "../vendor/lua-in-types/src/aot/ref/value.ts";
import { DRIVE, imageDir, libFile, progFile } from "./build-image.ts";
import { expectedPath, inputPath } from "./oracle.ts";
import { root, type Lib } from "./tslua.ts";

interface RefEntry {
  input: string;
  lib: Lib["name"];
  ops: number;
  blocks: number;
  luaCalls: number;
  builtinCalls: Record<string, number>;
  metamethods: Record<string, number>;
}

export interface GateRow {
  input: string;
  lib: Lib["name"];
  pass: boolean;
  /** Chunks written; the chunk at which the run ended (D or X), or undefined if it did not. */
  chunks: number;
  endedAt?: number;
  /** The last chunk whose state resolved (not any or never), and its tag. */
  lastGood: number;
  lastTag: string;
  output: string;
  error?: string;
  otherErrors: string[];
  instantiations: number;
  checkSeconds: number;
  wallSeconds: number;
  peakBytes: number;
  refOps: number;
  /** Trampoline steps per chunk of this run. */
  drive?: number;
  /** pass, or the class of the failure (see above), with a detail line. */
  kind: string;
  detail?: string;
}

const argv = process.argv.slice(2);
const opt = (k: string) => (argv.includes(k) ? argv[argv.indexOf(k) + 1] : undefined);
const sum = (o: Record<string, number>) => Object.values(o).reduce((a, b) => a + b, 0);

/** Trampoline steps per chunk: the image's (Step), or --drive N (RunWith on the program). */
const drive = Number(opt("--drive") ?? DRIVE);

/**
 * Budget chunks a check needs, from the reference's counters: the 40 inputs
 * of the first gate ended at 0.17-0.18 of this estimate, so 0.4 leaves 2x
 * headroom (a run that needs more reports "still running").
 */
export const chunksFor = (r: RefEntry): number => {
  const steps = 3 * (r.luaCalls + sum(r.metamethods) + sum(r.builtinCalls)) + r.blocks / 4 + 8;
  return Math.ceil((0.4 * steps) / drive) + 20;
};

const lit = JSON.stringify;

const header = (source: string, lib: Lib["name"], single: boolean) => [
  "// Generated by scripts/types-gate.ts; do not edit.",
  `import type { TSStart, TSStep, TSOutput, TSTag } from "../../../../src/index.ts";`,
  `import type { Prog } from "../../../../image/${progFile}";`,
  `import type { RunWith } from "../../../../vendor/lua-in-types/src/aot/types/run.ts";`,
  "type Equal<A, B> = (<T>() => T extends A ? 1 : 2) extends <T>() => T extends B ? 1 : 2 ? true : false;",
  'type Stat<S> = 0 extends 1 & S ? "any" : [S] extends [never] ? "never" : TSTag<S>;',
  drive === DRIVE
    ? "type Chunk<S> = TSStep<S>;"
    : `type Chunk<S> = RunWith<Prog, S, ${lit("x".repeat(drive))}>;`,
  `type One<S> = RunWith<Prog, S, ${single ? '"x"' : '""'}>;`,
  `type S0 = TSStart<${lit(toBytes(source))}, ${lit(lib)}>;`,
];

/** The CLI entry of one check. */
export function entryText(source: string, lib: Lib["name"], chunks: number, expected: string) {
  const lines = header(source, lib, false);
  for (let k = 1; k <= chunks; k++) lines.push(`type S${k} = Chunk<S${k - 1}>;`);
  const first = lines.length + 1;
  for (let k = 1; k <= chunks; k++) lines.push(`export const p${k}: 0 = null! as Stat<S${k}>;`);
  lines.push(`export const out: 0 = null! as TSOutput<S${chunks}>;`);
  lines.push(`export const ok: Equal<TSOutput<S${chunks}>, ${lit(toBytes(expected))}> = true;`);
  return { text: lines.join("\n") + "\n", probeLine: first, outLine: first + chunks };
}

/**
 * Chunks 1..k-1, then `singles` single trampoline steps (one statement each),
 * each followed by a probe line: where inside chunk k a run fails.
 */
export function stepText(source: string, lib: Lib["name"], k: number, singles: number) {
  const lines = header(source, lib, true);
  for (let c = 1; c < k; c++) lines.push(`type S${c} = Chunk<S${c - 1}>;`);
  lines.push(`type Q0 = S${k - 1};`);
  const at: number[] = [];
  for (let j = 1; j <= singles; j++) {
    lines.push(`type Q${j} = One<Q${j - 1}>;`);
    lines.push(`export const q${j}: 0 = null! as Stat<Q${j}>;`);
    at.push(lines.length - 1); // 1-based line of `type Q<j>`
  }
  return { text: lines.join("\n") + "\n", stepLine: (j: number) => at[j - 1]! };
}

/** A printed string literal type ("..." with escapes) back to its text. */
const unquote = (t: string): string => {
  try {
    return JSON.parse(t) as string;
  } catch {
    return t;
  }
};

const timeoutSec = Number(opt("--timeout") ?? 900);

function runTsrs(
  dir: string,
): Promise<{ out: string; wall: number; peak: number; timedOut: boolean }> {
  const t0 = performance.now();
  return new Promise((resolve, reject) => {
    const p = spawn(
      "/usr/bin/time",
      [
        "-l",
        join(root, "node_modules/.bin/tsrs"),
        "--noEmit",
        "--fast",
        "--extendedDiagnostics",
        "--pretty",
        "false",
        "--noErrorTruncation",
        "-p",
        dir,
      ],
      // Its own process group, so that a timeout kills tsrs too.
      { env: { ...process.env, TSRS_FAST: "1" }, detached: true },
    );
    let timedOut = false;
    const timer = setTimeout(() => {
      timedOut = true;
      try {
        process.kill(-p.pid!, "SIGKILL");
      } catch {
        // already gone
      }
    }, timeoutSec * 1000);
    let out = "";
    p.stdout.on("data", (d: Buffer) => (out += d.toString()));
    p.stderr.on("data", (d: Buffer) => (out += d.toString()));
    p.on("error", reject);
    p.on("close", () => {
      clearTimeout(timer);
      const peak = Number(/(\d+)\s+maximum resident set size/.exec(out)?.[1] ?? 0);
      resolve({ out, wall: (performance.now() - t0) / 1000, peak, timedOut });
    });
  });
}

const maxOps = Number(opt("--max-ops") ?? 10_000_000);
const dirOf = (lib: Lib["name"], input: string) =>
  join(root, ".run/gate", lib, input.replaceAll("/", "__"));

async function main() {
  for (const f of [progFile, libFile("mini"), libFile("es5")])
    if (!existsSync(join(imageDir, f))) throw new Error(`image/${f} is missing: run vp run build`);
  const imageTime = statSync(join(imageDir, progFile)).mtimeMs;
  const manifest = JSON.parse(
    readFileSync(join(root, "oracle/ref-image-manifest.json"), "utf8"),
  ) as { entries: RefEntry[] };
  const libArg = opt("--lib") ?? "mini";
  const libNames: Lib["name"][] = libArg === "both" ? ["mini", "es5"] : [libArg as Lib["name"]];
  const jobs = Number(opt("--jobs") ?? 3);
  const only = opt("--only");
  // Inputs ordered by the reference's cost in the mini lib mode.
  let inputs = manifest.entries
    .filter((e) => e.lib === "mini")
    .sort((a, b) => a.ops - b.ops)
    .map((e) => e.input);
  if (only !== undefined) inputs = inputs.filter((n) => n.includes(only));
  else if (!argv.includes("--all")) inputs = inputs.slice(0, Number(opt("--n") ?? 20));

  const rows: GateRow[] = [];
  // Both lib modes share one queue, cheapest first.
  const work = libNames
    .flatMap((lib) =>
      inputs.map((input) => {
        const ref = manifest.entries.find((e) => e.input === input && e.lib === lib)!;
        return { input, lib, ref };
      }),
    )
    .sort((a, b) => a.ref.ops - b.ref.ops);
  console.log(`${work.length} checks (${libNames.join(", ")}), ${jobs} tsrs at a time`);
  let next = 0;
  await Promise.all(
    Array.from({ length: Math.min(jobs, work.length) }, async () => {
      while (next < work.length) {
        const w = work[next++]!;
        const rowPath = join(dirOf(w.lib, w.input), "row.json");
        let row: GateRow;
        if (
          argv.includes("--resume") &&
          existsSync(rowPath) &&
          statSync(rowPath).mtimeMs > imageTime &&
          (JSON.parse(readFileSync(rowPath, "utf8")) as GateRow).drive === drive
        )
          row = JSON.parse(readFileSync(rowPath, "utf8")) as GateRow;
        else {
          const source = readFileSync(inputPath(w.input), "utf8");
          const expected = readFileSync(expectedPath(w.input, w.lib), "utf8");
          row =
            w.ref.ops > maxOps
              ? skipped(w.input, w.lib, w.ref.ops)
              : await gateOne({ ...w, source, expected }, w.lib);
          mkdirSync(dirOf(w.lib, w.input), { recursive: true });
          writeFileSync(rowPath, JSON.stringify(row, null, 1) + "\n");
        }
        rows.push(row);
        console.log(`[${rows.length}/${work.length}] ${rowText(row)}`);
      }
    }),
  );
  for (const lib of libNames) {
    const mine = rows.filter((r) => r.lib === lib).sort((a, b) => a.refOps - b.refOps);
    writeFileSync(
      join(root, ".run/gate", lib, "report.json"),
      JSON.stringify(mine, null, 1) + "\n",
    );
    console.log(`${lib}: ${mine.filter((r) => r.pass).length}/${mine.length} pass`);
  }
  if (argv.includes("--doc")) {
    writeFileSync(join(root, "docs/GATE.md"), gateDoc(rows));
    console.log("wrote docs/GATE.md");
  }
  if (rows.some((r) => !r.pass)) process.exitCode = 1;
}

const skipped = (input: string, lib: Lib["name"], refOps: number): GateRow => ({
  input,
  lib,
  pass: false,
  chunks: 0,
  lastGood: 0,
  lastTag: "",
  output: "",
  otherErrors: [],
  instantiations: 0,
  checkSeconds: 0,
  wallSeconds: 0,
  peakBytes: 0,
  refOps,
  drive,
  kind: "skipped",
  detail: `the reference runs ${refOps} ops (over --max-ops ${maxOps})`,
});

interface Work {
  input: string;
  ref: RefEntry;
  source: string;
  expected: string;
}

const writeProject = (dir: string, text: string) => {
  mkdirSync(dir, { recursive: true });
  writeFileSync(join(dir, "run.ts"), text);
  writeFileSync(
    join(dir, "tsconfig.json"),
    JSON.stringify({
      extends: "../../../../tsconfig.json",
      include: ["run.ts"],
      exclude: [],
      compilerOptions: { noUnusedLocals: false },
    }) + "\n",
  );
};

const diagnostics = (out: string) =>
  [...out.matchAll(/run\.ts\((\d+),\d+\): error (TS\d+): (.*)/g)].map((m) => ({
    line: Number(m[1]),
    code: m[2]!,
    message: m[3]!,
  }));
const countOf = (out: string) => Number(/Instantiations:\s+(\d+)/.exec(out)?.[1] ?? NaN);

async function gateOne(w: Work, lib: Lib["name"]): Promise<GateRow> {
  const chunks = chunksFor(w.ref);
  const dir = dirOf(lib, w.input);
  const e = entryText(w.source, lib, chunks, w.expected);
  writeProject(dir, e.text);
  const { out, wall, peak, timedOut } = await runTsrs(dir);
  writeFileSync(join(dir, "tsrs.log"), out);
  const tags = new Map<number, string>();
  let output = "";
  let okFailed = false;
  const otherErrors: string[] = [];
  let deep: number | undefined;
  for (const d of diagnostics(out)) {
    const t = /^Type '([\s\S]*)' is not assignable to type '0'\.$/.exec(d.message);
    if (d.line >= e.probeLine && d.line < e.outLine && t)
      tags.set(d.line - e.probeLine + 1, unquote(t[1]!));
    else if (d.line === e.outLine && t) output = unquote(t[1]!);
    else if (d.line === e.outLine + 1) okFailed = true;
    else {
      // `type S<k> = ...` is line k + (the header's length).
      if (d.code === "TS2589" && deep === undefined) deep = d.line - (e.probeLine - chunks - 1);
      otherErrors.push(`${d.line}: ${d.code} ${d.message.slice(0, 200)}`);
    }
  }
  let endedAt: number | undefined;
  let lastGood = 0;
  let lastTag = "";
  for (let k = 1; k <= chunks; k++) {
    const t = tags.get(k) ?? "?";
    if (t === "any" || t === "never" || t === "?") break;
    lastGood = k;
    lastTag = t;
    if (t === "D" || t === "X") {
      endedAt = k;
      break;
    }
  }
  const pass = !timedOut && !okFailed && otherErrors.length === 0 && endedAt !== undefined;
  const row: GateRow = {
    input: w.input,
    lib,
    pass,
    chunks,
    endedAt,
    lastGood,
    lastTag,
    output,
    error: output.startsWith("error: ") ? output.slice(7).trimEnd() : undefined,
    otherErrors,
    instantiations: countOf(out),
    checkSeconds: Number(/Check time:\s+([\d.]+)s/.exec(out)?.[1] ?? NaN),
    wallSeconds: wall,
    peakBytes: peak,
    refOps: w.ref.ops,
    drive,
    kind: "pass",
  };
  if (pass) return row;
  if (timedOut) {
    row.kind = "timeout";
    row.detail = `killed after ${timeoutSec} s`;
  } else if (deep !== undefined) {
    Object.assign(row, await classify2589(w, lib, deep));
  } else if (row.error !== undefined) {
    const gap = /([\w.]+) is not supported in types/.exec(row.error);
    row.kind = gap ? "runtime gap" : "Lua error";
    row.detail = gap ? gap[0] : row.error;
  } else if (endedAt === undefined) {
    const t = tags.get(lastGood + 1);
    row.kind = t === "any" || t === "never" ? "broken state" : "unfinished";
    row.detail =
      row.kind === "unfinished"
        ? `still running after ${chunks} chunks`
        : `chunk ${lastGood + 1} is ${t}${otherErrors.length ? `; ${otherErrors[0]}` : ""}`;
  } else if (okFailed) {
    row.kind = "wrong output";
    const got = output.split("\n");
    const want = w.expected.split("\n");
    const i = got.findIndex((l, k) => l !== want[k]);
    const at = i < 0 ? got.length : i;
    row.detail = `line ${at + 1}: got ${lit(got[at] ?? "(end)")}, expected ${lit(want[at] ?? "(end)")}`;
  } else {
    row.kind = "other";
    row.detail = otherErrors[0];
  }
  return row;
}

/**
 * A TS2589 in chunk k: rerun chunk k one trampoline step per statement. If
 * every step fits, the chunk as a whole went over the budget (count). If a
 * step fails, compare the instantiations with and without that step: at
 * least ~5M is the count limit, fewer is a depth limit.
 */
async function classify2589(
  w: Work,
  lib: Lib["name"],
  k: number,
): Promise<{ kind: string; detail: string }> {
  const dir = join(dirOf(lib, w.input), "steps");
  const a = stepText(w.source, lib, k, drive);
  writeProject(dir, a.text);
  const ra = await runTsrs(dir);
  writeFileSync(join(dir, "tsrs.log"), ra.out);
  const bad = diagnostics(ra.out).find((d) => d.code === "TS2589");
  if (ra.timedOut)
    return { kind: "TS2589 (unclassified)", detail: `chunk ${k}; the step rerun timed out` };
  if (bad === undefined)
    return {
      kind: "TS2589 count",
      detail: `chunk ${k} (${drive} steps) over the budget; each of its steps alone fits`,
    };
  let j = 1;
  // The error sits on `type Q<j>` or on its probe line.
  while (j < drive && a.stepLine(j) !== bad.line && a.stepLine(j) + 1 !== bad.line) j++;
  const without = stepText(w.source, lib, k, j - 1);
  const withIt = stepText(w.source, lib, k, j);
  writeProject(join(dir, "b"), without.text);
  writeProject(join(dir, "c"), withIt.text);
  const [rb, rc] = await Promise.all([runTsrs(join(dir, "b")), runTsrs(join(dir, "c"))]);
  const cost = countOf(rc.out) - countOf(rb.out);
  return cost >= 4_900_000
    ? {
        kind: "TS2589 count",
        detail: `chunk ${k}, step ${j} alone costs ${(cost / 1e6).toFixed(1)}M instantiations`,
      }
    : {
        kind: "TS2589 depth",
        detail: `chunk ${k}, step ${j} fails after ${(cost / 1e6).toFixed(2)}M instantiations`,
      };
}

export const rowText = (r: GateRow): string =>
  [
    r.pass ? "PASS" : "FAIL",
    `${r.lib}/${r.input}`,
    r.endedAt !== undefined
      ? `ended at chunk ${r.endedAt}/${r.chunks} (${r.lastTag})`
      : `reached chunk ${r.lastGood}/${r.chunks} (${r.lastTag || "nothing"})`,
    `${(r.instantiations / 1e6).toFixed(0)}M inst`,
    `check ${r.checkSeconds.toFixed(1)} s (wall ${r.wallSeconds.toFixed(1)} s)`,
    `peak ${(r.peakBytes / 2 ** 30).toFixed(1)} GB`,
    `ref ${r.refOps} ops`,
    ...(r.pass ? [] : [`${r.kind}: ${r.detail ?? ""}`]),
  ].join("  ");

const category = (input: string) =>
  input.startsWith("upstream/")
    ? "upstream"
    : input.startsWith("extreme/")
      ? "extremes"
      : "hand-written";

const quant = (xs: number[]) => {
  const v = [...xs].sort((a, b) => a - b);
  const q = (p: number) => v[Math.min(v.length - 1, Math.floor(p * (v.length - 1) + 0.5))]!;
  return v.length ? [v[0]!, q(0.5), q(0.9), v[v.length - 1]!] : [];
};

/** docs/GATE.md: the results of a full run. */
export function gateDoc(rows: GateRow[]): string {
  const libsSeen = [...new Set(rows.map((r) => r.lib))].sort().reverse();
  const out: string[] = [
    "# The types gate",
    "",
    "Generated by `scripts/types-gate.ts` (`vp run gate:types -- --all --lib both --jobs 3 --doc`); do not edit.",
    "",
    `Every oracle input checked by tslua inside tsrs (the image of \`vp run build\`, ${drive} trampoline steps per CLI chunk), compared byte for byte with \`oracle/expected/\`. Inputs whose reference run exceeds ${maxOps.toLocaleString("en")} IR ops are skipped; each tsrs run gets ${timeoutSec} s.`,
    "",
    "## Pass rate",
    "",
    `| category | ${libsSeen.join(" | ")} |`,
    `| --- | ${libsSeen.map(() => "---:").join(" | ")} |`,
  ];
  for (const c of ["hand-written", "upstream", "extremes", "all"]) {
    const cells = libsSeen.map((lib) => {
      const rs = rows.filter((r) => r.lib === lib && (c === "all" || category(r.input) === c));
      return `${rs.filter((r) => r.pass).length} / ${rs.length}`;
    });
    out.push(`| ${c} | ${cells.join(" | ")} |`);
  }
  const fmt = (x: number, unit: string) =>
    unit === "M"
      ? `${(x / 1e6).toFixed(x < 1e7 ? 1 : 0)}M`
      : unit === "GB"
        ? `${(x / 2 ** 30).toFixed(1)} GB`
        : unit === "s"
          ? `${x.toFixed(1)} s`
          : unit === "k"
            ? `${(x / 1e3).toFixed(0)}k`
            : x.toLocaleString("en");
  out.push(
    "",
    "## Passing checks",
    "",
    "Min / median / p90 / max over the passing checks. Chunks: CLI statements to the end of the run; time: tsrs's check time; memory: max RSS; ratio: instantiations per reference IR op.",
    "",
    "| lib | n | reference ops | chunks | instantiations | time | memory | instantiations / op |",
    "| --- | ---: | --- | --- | --- | --- | --- | --- |",
  );
  for (const lib of libsSeen) {
    const ps = rows.filter((r) => r.lib === lib && r.pass);
    const col = (xs: number[], unit: string) =>
      quant(xs)
        .map((x) => fmt(x, unit))
        .join(" / ");
    out.push(
      `| ${lib} | ${ps.length} | ${col(
        ps.map((r) => r.refOps),
        "k",
      )} | ${col(
        ps.map((r) => r.endedAt ?? 0),
        "",
      )} | ${col(
        ps.map((r) => r.instantiations),
        "M",
      )} | ${col(
        ps.map((r) => r.checkSeconds),
        "s",
      )} | ${col(
        ps.map((r) => r.peakBytes),
        "GB",
      )} | ${col(
        ps.map((r) => r.instantiations / r.refOps),
        "",
      )} |`,
    );
  }
  out.push("", "## Failures", "");
  const fails = rows.filter((r) => !r.pass);
  if (fails.length === 0) out.push("None.");
  const groupKey = (r: GateRow) =>
    r.kind === "runtime gap"
      ? `runtime gap: ${r.detail}`
      : r.kind === "Lua error"
        ? `Lua error: ${r.detail}`
        : r.kind;
  const groups = new Map<string, GateRow[]>();
  for (const r of fails) groups.set(groupKey(r), [...(groups.get(groupKey(r)) ?? []), r]);
  for (const [k, rs] of [...groups].sort((a, b) => b[1].length - a[1].length)) {
    out.push(
      `### ${k} (${rs.length})`,
      "",
      "| input | lib | reference ops | detail |",
      "| --- | --- | ---: | --- |",
    );
    for (const r of rs.sort((a, b) => a.refOps - b.refOps))
      out.push(
        `| ${r.input} | ${r.lib} | ${r.refOps.toLocaleString("en")} | ${(r.kind === "runtime gap" || r.kind === "Lua error" ? `chunk ${r.endedAt ?? r.lastGood}` : (r.detail ?? "")).replaceAll("|", "\\|")} |`,
      );
    out.push("");
  }
  return out.join("\n").trimEnd() + "\n";
}

