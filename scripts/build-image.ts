// The type-level image: tslua compiled to type aliases (lua-in-types'
// emitter), started from the boot image, with the per-check =check entry and
// INPUT as a type parameter.
//
//   vp run build        -> image/tslua.prog.d.ts, image/tslua.<lib>.d.ts (git-ignored)
//
// The snapshots image/boot.<lib>.json (vp run boot; built here when missing)
// hold the same program, so the program's code (every proto's segments and
// the `Prog` interface, ~267 MB) is written once, to tslua.prog.d.ts, and each
// lib mode gets only its boot heap and start state (tslua.<lib>.d.ts):
//
//   S0<INPUT>   the start state: =check called with INPUT set (a byte string)
//   Step<S>     one budget chunk (DRIVE trampoline steps; CLI statements)
//
// src/index.ts wraps them as TS<>, TSMini<> (hovers: one alias, refuelled by
// src/hover.ts) and TSStart/TSStep/TSOutput (CLI chunks).
// Both files are declaration files: tsrs (with skipLibCheck) resolves only
// what a run touches (docs/AOT.md, "Emitter").
import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { emitFromSnapshot, type Emitted } from "../vendor/lua-in-types/src/aot/emit/emit.ts";
import type { Snapshot } from "../vendor/lua-in-types/src/aot/ref/snapshot.ts";
import { imagePath, refProgram } from "./luaref.ts";
import { libs, root, type Lib } from "./tslua.ts";

/**
 * Trampoline steps per budget chunk. tslua's steps cost up to ~65k
 * instantiations; lua-in-types settled on 50, but with 50 one chunk of
 * upstream/superWithTypeArgument goes over the checker's budget (TS2589)
 * and with 10 it runs to the end, so 25.
 */
export const DRIVE = 25;
export const imageDir = join(root, "image");
export const progFile = "tslua.prog.d.ts";
export const libFile = (lib: Lib["name"]): string => `tslua.${lib}.d.ts`;
/** The runtime (vendor/lua-in-types/src/aot/types/) as the image files import it. */
const RUNTIME = "../vendor/lua-in-types/src/aot/types/";

const PROG_HEAD = "export interface Prog extends ProgBase {\n";

/** Split an emitted body into the program's code (through the Prog interface) and the lib's image. */
function split(e: Emitted): { code: string; image: string } {
  const at = e.body.indexOf(PROG_HEAD);
  if (at < 0 || e.body.indexOf(PROG_HEAD, at + 1) >= 0)
    throw new Error("build-image: expected exactly one Prog interface in the emitted body");
  const end = e.body.indexOf("\n}\n", at);
  if (end < 0) throw new Error("build-image: unterminated Prog interface");
  const code = e.body.slice(0, end + 3);
  const image = e.body.slice(end + 3);
  if (!/^export type HeapI = /m.test(image) || !/^export type S0<G0 = undefined> = /m.test(image))
    throw new Error("build-image: the image part lacks HeapI or S0<G0>");
  return { code, image };
}

const header = (what: string) =>
  `// Generated by scripts/build-image.ts (vp run build); do not edit.\n// ${what}\n`;

async function main() {
  const t0 = performance.now();
  for (const lib of Object.values(libs))
    if (!existsSync(imagePath(lib.name))) {
      console.log(`image/boot.${lib.name}.json is missing: running vp run boot`);
      execFileSync("node", [join(root, "scripts/boot.ts")], { stdio: "inherit" });
      break;
    }
  mkdirSync(imageDir, { recursive: true });
  const program = refProgram();
  console.log(`linked ${program.protos.length} protos (${secs(t0)})`);

  let shared: { code: string; imports: string } | undefined;
  const sizes: Record<string, number> = {};
  for (const lib of Object.values(libs)) {
    const t1 = performance.now();
    const snap = JSON.parse(readFileSync(imagePath(lib.name), "utf8")) as Snapshot;
    const entry = program.modules[`\0check.${lib.name}`];
    if (entry === undefined) throw new Error(`no =check chunk for ${lib.name}`);
    const e = emitFromSnapshot(program, snap, entry, ["INPUT"], { runtime: RUNTIME, drive: DRIVE });
    const { code, image } = split(e);
    if (shared === undefined) shared = { code, imports: e.imports };
    else if (shared.code !== code || shared.imports !== e.imports)
      throw new Error(`build-image: the ${lib.name} program differs from the first lib's`);
    const dr = JSON.stringify("x".repeat(DRIVE));
    const text = `${header(`tslua's boot heap and start state with ${lib.file} (image/boot.${lib.name}.json).`)}${e.imports}
import type { RunWith } from "${RUNTIME}run.ts";
import type { Prog } from "./${progFile}";
${image}
/** One budget chunk of the run (${DRIVE} trampoline steps): CLI statements chain these. */
export type Step<S> = RunWith<Prog, S, ${dr}>;
`;
    writeFileSync(join(imageDir, libFile(lib.name)), text);
    sizes[libFile(lib.name)] = text.length;
    console.log(
      `${lib.name}: emitted ${e.stats.protos} protos, ${e.stats.blocks} blocks, ${e.stats.segments} segments; image ${mb(text.length)} (${secs(t1)})`,
    );
  }
  const prog = `${header("tslua's code: every proto's segments and the Prog interface, shared by the lib modes.")}${shared!.imports}\n\n${shared!.code}`;
  writeFileSync(join(imageDir, progFile), prog);
  sizes[progFile] = prog.length;
  console.log(
    `wrote ${Object.entries(sizes)
      .map(([f, n]) => `image/${f} (${mb(n)})`)
      .join(", ")} in ${secs(t0)}`,
  );
}

const secs = (t: number) => `${((performance.now() - t) / 1000).toFixed(1)} s`;
const mb = (n: number) => `${(n / 1e6).toFixed(1)} MB`;

if (import.meta.main) await main();
